"""Build the self-contained notebook for WASM/Pyodide export.

The repo notebook (``drylab_nb.py``) imports the ``drylab``
package — the single source of truth. Pyodide can't import sibling packages
from a static export, so this tool emits ``dist/drylab_wasm_nb.py``:
the same notebook with the cell between the ``[[INLINE:drylab:...]]``
sentinels replaced by an embedded copy of every package module,
base64-encoded and registered through ``importlib`` so intra-package
(relative) imports run unchanged.

The generated file is a build artifact: never edit it, always regenerate.
Its name carries the package version (stamped inside too), so successive
deliveries don't collide (charter §10).

Usage:  python tools/build_wasm_notebook.py
Then:   marimo export html-wasm dist/drylab_wasm_nb_v<ver>.py -o site --mode run
"""

from __future__ import annotations

import base64
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
NOTEBOOK = REPO / "drylab_nb.py"
DIST = REPO / "dist"

# (module name, path) in dependency order; packages get their __init__ source
# exec'd into a pre-created module so submodule imports resolve.
MODULES: list[tuple[str, Path]] = [
    ("drylab.data", REPO / "drylab/data.py"),
    ("drylab.bandshape", REPO / "drylab/bandshape.py"),
    ("drylab.formulae", REPO / "drylab/formulae.py"),
    ("drylab.craig", REPO / "drylab/craig.py"),
    ("drylab.gc", REPO / "drylab/gc.py"),
    ("drylab.ce", REPO / "drylab/ce.py"),
    ("drylab.gc_program", REPO / "drylab/gc_program.py"),
    ("drylab.diagnostics", REPO / "drylab/diagnostics.py"),
    ("drylab.gradient", REPO / "drylab/gradient.py"),
    ("drylab.model", REPO / "drylab/model.py"),
    ("drylab.plotting.config", REPO / "drylab/plotting/config.py"),
    ("drylab.plotting.base", REPO / "drylab/plotting/base.py"),
    ("drylab.plotting.chromatogram", REPO / "drylab/plotting/chromatogram.py"),
    ("drylab.plotting.sweep", REPO / "drylab/plotting/sweep.py"),
    ("drylab.plotting.gradient", REPO / "drylab/plotting/gradient.py"),
    ("drylab.plotting.craig", REPO / "drylab/plotting/craig.py"),
    ("drylab.plotting.ce", REPO / "drylab/plotting/ce.py"),
    ("drylab.plotting.gc", REPO / "drylab/plotting/gc.py"),
    ("drylab.plotting.bandshape", REPO / "drylab/plotting/bandshape.py"),
]
PACKAGE_INITS: list[tuple[str, Path]] = [
    ("drylab", REPO / "drylab/__init__.py"),
    ("drylab.plotting", REPO / "drylab/plotting/__init__.py"),
]

BEGIN = "# [[INLINE:drylab:BEGIN]]"
END = "# [[INLINE:drylab:END]]"


def encoded(path: Path) -> str:
    if not path.is_file():
        raise FileNotFoundError(f"Module source missing: {path}")
    return base64.b64encode(path.read_text().encode()).decode()


def build_inline_body(indent: str) -> str:
    lines: list[str] = []
    lines.append("# --- embedded drylab (generated by tools/build_wasm_notebook.py;")
    lines.append("#     do not edit — edit the package and rebuild) ---")
    lines.append("import base64 as _b64")
    lines.append("import importlib.util as _ilu")
    lines.append("import sys as _sys")
    lines.append("")
    lines.append("_SOURCES = {")
    for name, path in MODULES + PACKAGE_INITS:
        lines.append(f"    {name!r}: {encoded(path)!r},")
    lines.append("}")
    lines.append("")
    lines.append("def _register(name, is_pkg=False):")
    lines.append("    spec = _ilu.spec_from_loader(name, loader=None, is_package=is_pkg)")
    lines.append("    mod = _ilu.module_from_spec(spec)")
    lines.append("    _sys.modules[name] = mod")
    lines.append("    return mod")
    lines.append("")
    lines.append("def _exec_into(name, module):")
    lines.append("    src = _b64.b64decode(_SOURCES[name]).decode()")
    lines.append("    exec(compile(src, f'<embedded {name}>', 'exec'), module.__dict__)")
    lines.append("")
    lines.append("if 'drylab' not in _sys.modules:")
    lines.append("    _pkg = _register('drylab', is_pkg=True)")
    lines.append("    _sub = _register('drylab.plotting', is_pkg=True)")
    for name, _ in MODULES:
        lines.append(f"    _exec_into({name!r}, _register({name!r}))")
    lines.append("    _exec_into('drylab', _pkg)")
    lines.append("    _exec_into('drylab.plotting', _sub)")
    lines.append("")
    # The import statements are NOT restated here: they are extracted from
    # the notebook's own [[INLINE]] cell, so adding an export to the notebook
    # cannot desynchronize the WASM build (this restatement broke three times
    # before being derived; see issues.md "WASM builder import list").
    nb_src = NOTEBOOK.read_text()
    block = nb_src[nb_src.index(BEGIN) + len(BEGIN):nb_src.index(END)]
    version_line = "DRYLAB_VERSION = drylab.__version__"
    if version_line not in block:
        raise SystemExit("INLINE cell no longer assigns DRYLAB_VERSION; "
                         "update build_wasm_notebook.py to match")
    block = block.replace(version_line,
                          version_line + " + ' (embedded)'")
    for raw in block.splitlines():
        lines.append(raw.strip("\n").removeprefix("    "))
    return "\n".join(indent + ln if ln else "" for ln in lines)


def main() -> int:
    src = NOTEBOOK.read_text()
    begin_matches = [m for m in re.finditer(re.escape(BEGIN), src)]
    end_matches = [m for m in re.finditer(re.escape(END), src)]
    if len(begin_matches) != 1 or len(end_matches) != 1:
        raise RuntimeError(
            f"Expected exactly one BEGIN and one END sentinel in {NOTEBOOK.name}; "
            f"found {len(begin_matches)} BEGIN, {len(end_matches)} END"
        )
    b, e = begin_matches[0], end_matches[0]
    if e.start() <= b.end():
        raise RuntimeError("END sentinel precedes BEGIN sentinel")

    # Indentation of the sentinel line = cell-body indentation.
    line_start = src.rfind("\n", 0, b.start()) + 1
    indent = src[line_start : b.start()]
    if indent.strip():
        raise RuntimeError(f"BEGIN sentinel not at start of line: {indent!r}")

    body = build_inline_body(indent)
    out_src = src[: b.end()] + "\n" + body + "\n" + indent + src[e.start() :]

    # Version stamp from the package itself — one source of truth.
    sys.path.insert(0, str(REPO))
    import drylab  # noqa: E402

    version = drylab.__version__
    # A module present in drylab/ but absent from MODULES is embedded
    # NOWHERE, and the failure surfaces only when the exported notebook
    # runs — where marimo's show_tracebacks:false hides it. This check
    # existed as an open issue until adding gc_program.py demonstrated the
    # hazard concretely; the inventory is still hand-maintained, but an
    # omission is now a build failure rather than a broken artifact.
    # Modules deliberately NOT embedded, each with a stated reason. Empty
    # now that drylab/ce.py is licensed (see NOTICE.md); the mechanism
    # stays because the unregistered-module check must keep its teeth --
    # an omission is a build failure unless it is listed here on purpose.
    EXCLUDED: dict = {}
    for path, reason in EXCLUDED.items():
        if path.exists():
            print(f"  excluding {path.relative_to(REPO)}: {reason}")
    registered = ({p.resolve() for _, p in MODULES + PACKAGE_INITS}
                  | {p.resolve() for p in EXCLUDED})
    on_disk = {p.resolve() for p in (REPO / "drylab").rglob("*.py")}
    unregistered = sorted(p.relative_to(REPO).as_posix()
                          for p in on_disk - registered)
    if unregistered:
        raise SystemExit(
            f"These modules exist in drylab/ but are not in MODULES, so "
            f"they would be missing from the artifact: {unregistered}. Add "
            f"them to tools/build_wasm_notebook.py in dependency order.")
    stale = sorted(p.relative_to(REPO).as_posix()
                   for p in registered - on_disk
                   if p not in {q.resolve() for q in EXCLUDED})
    if stale:
        raise SystemExit(
            f"MODULES lists files that no longer exist: {stale}")
    # Version stamp INSIDE the artifact (charter section 10), so a file
    # separated from its filename is still self-identifying. Anchored on the
    # module docstring's STRUCTURE, not on its title text: the previous
    # anchor was the literal title 'HPLC Simulator (marimo)', which the
    # v0.9.1 rename to 'Chromatography Simulator' invalidated. str.replace
    # on a missing needle is a silent no-op, so v0.9.1, v0.10.0 and v0.10.1
    # all shipped unstamped with nothing to report it. Guarded below so the
    # same class of failure raises instead of passing quietly.
    # A '"""' at column 0 matches only the module docstring; every cell
    # docstring in a marimo notebook is indented inside a function.
    doc_open = re.search(r'^"""[^\n]*$', out_src, re.M)
    if doc_open is None:
        raise SystemExit(
            "Notebook has no module-level docstring to stamp the build "
            "version into; update tools/build_wasm_notebook.py with a new "
            "anchor before it can produce a self-identifying artifact."
        )
    out_src = (
        out_src[: doc_open.end()]
        + f"\n\nSelf-contained WASM build v{version}, generated by "
        f"tools/build_wasm_notebook.py from the drylab package.\n"
        f"Build artifact: never edit this file, always regenerate it."
        + out_src[doc_open.end():]
    )

    DIST.mkdir(exist_ok=True)
    out_path = DIST / f"drylab_wasm_nb_v{version.replace('.', '_')}.py"
    out_path.write_text(out_src)

    # Verify: the generated file must compile and the embedded package must
    # import in a namespace where the repo package is masked.
    compile(out_src, str(out_path), "exec")
    print(f"Wrote {out_path.relative_to(REPO)} ({len(out_src):,} chars)")
    print("Next: marimo export html-wasm", out_path.relative_to(REPO), "-o site --mode run")
    return 0


if __name__ == "__main__":
    sys.exit(main())
